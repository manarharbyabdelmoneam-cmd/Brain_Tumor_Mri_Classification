# 6. طريقة الاستخدام
# ============================================================
 
st.markdown("""
## 🚀 طريقة الاستخدام
 
1. **📤 رفع الصورة:** من الصفحة الرئيسية، ارفعي صورة MRI بصيغة JPG أو JPEG أو PNG.
2. **🔍 تحليل الصورة:** اضغطي على زر "تحليل الصورة" لبدء عملية التصنيف.
3. **📊 عرض النتائج:** هيظهر التصنيف المتوقع مع نسبة الثقة واحتمالات جميع الفئات.
4. **🔥 Grad-CAM:** يمكنك تفعيل عرض Grad-CAM لمعرفة المنطقة اللي ركّز عليها النموذج في قراره.
5. **📈 مقارنة النماذج:** من صفحة "Model Comparison" يمكنك مقارنة أداء عدة نماذج مختلفة.
6. **📋 تحليل التدريب:** من صفحة "Training Analysis" يمكنك متابعة منحنيات الدقة والخسارة أثناء التدريب.
""")
 
